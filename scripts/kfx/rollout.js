#!/usr/bin/env node
// scripts/kfx/rollout.js · puts the cinematic motion layer on every public page
//
//   node scripts/kfx/rollout.js          write changes
//   node scripts/kfx/rollout.js --check  exit 1 if any page is missing or stale
//
// Idempotent: the block between <!-- kfx:begin --> and <!-- kfx:end --> is
// rebuilt on every run, legacy patches are applied once. New public pages are
// picked up automatically; add private ones to EXCLUDE.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const V = 'kfx1';
// app, admin, account and utility pages keep their own UI untouched
const EXCLUDE = new Set([
  'account.html', 'admin-os.html', 'admin.html', 'app.html', 'dashboard.html', 'expense.html',
  'offline.html', 'statement.html', 'tax-report.html', 'test.html', 'unsubscribe.html', 'seo.html'
]);
const ARTICLE = new Set(['privacy.html', 'terms.html', 'docs.html']);
const LITE = new Set(['404.html', 'cancel.html', 'thanks.html', 'upgrade.html', 'welcome.html', 'win-back.html']);
const LANG_DIRS = ['ar', 'fr', 'it', 'ru'];

function listPages() {
  const out = [];
  fs.readdirSync(ROOT).filter((f) => f.endsWith('.html') && !EXCLUDE.has(f)).sort().forEach((f) => out.push(f));
  LANG_DIRS.forEach((dir) => {
    const p = path.join(ROOT, dir);
    if (!fs.existsSync(p)) return;
    fs.readdirSync(p).filter((f) => f.endsWith('.html')).sort().forEach((f) => out.push(dir + '/' + f));
  });
  const blog = path.join(ROOT, 'blog');
  if (fs.existsSync(blog)) fs.readdirSync(blog).filter((f) => f.endsWith('.html')).sort().forEach((f) => out.push('blog/' + f));
  return out;
}

function profileOf(rel) {
  if (rel === 'index.html') return 'home';
  if (rel.startsWith('blog/') || ARTICLE.has(rel)) return 'article';
  if (LITE.has(rel)) return 'lite';
  return 'page';
}

// runs before first paint: marks the page for the motion layer (the page keeps
// its own white + blue look and theme toggle), hands motion over from the legacy
// scripts, arms the homepage preloader once per session and a failsafe that
// shows everything.
// ?kfx=off on any URL skips the whole layer (old look and motion) for comparison.
function bootScript(profile) {
  const preload = profile === 'home'
    ? "try{if(!sessionStorage.getItem('kfx-pl')){h.classList.add('kfx-preload');sessionStorage.setItem('kfx-pl','1')}}catch(e){}"
    : '';
  return "<script>(function(d,w){var h=d.documentElement;if(/[?&]kfx=off\\b/.test(w.location.search)){w.__kfxOff=true;return}w.__kfxT0=(w.performance&&performance.now)?performance.now():0;" +
    "d.addEventListener('DOMContentLoaded',function(){w.__kfxDCL=true});" +
    "h.classList.add('kfx-js');" +
    "var rm=false;try{rm=w.matchMedia('(prefers-reduced-motion: reduce)').matches}catch(e){}" +
    "if(rm){h.classList.add('kfx-reduced')}else{w.kflPremiumMotionInit=true;w.kflParallaxInit=true;" + preload + "}" +
    "w.setTimeout(function(){if(!w.__kfxReady){h.classList.add('kfx-fail');h.classList.remove('kfx-preload')}},3500)})(document,window);</script>";
}

function block(profile) {
  const s = (src) => '<script defer src="' + src + '?v=' + V + '"></script>';
  return [
    '<!-- kfx:begin · cinematic motion layer · generated by scripts/kfx/rollout.js, edit there -->',
    bootScript(profile),
    '<meta name="kfx-profile" content="' + profile + '">',
    '<link rel="stylesheet" href="/css/lenis.css?v=' + V + '">',
    '<link rel="stylesheet" href="/css/kfx-motion.css?v=' + V + '">',
    s('/js/vendor/gsap.min.js'),
    s('/js/vendor/ScrollTrigger.min.js'),
    s('/js/vendor/SplitText.min.js'),
    s('/js/vendor/lenis.min.js'),
    profile === 'home' ? s('/js/kfx-home.js') : null,
    s('/js/kfx-motion.js'),
    '<!-- kfx:end -->'
  ].filter(Boolean).join('\n');
}

// legacy inline motion: step aside when the motion layer is in charge
const PATCHES = [
  { find: /\(function premiumMotion\(\)\{\n(?!\s*if \(window\.kflPremiumMotionInit\) return;)/g,
    put: "(function premiumMotion(){\n    if (window.kflPremiumMotionInit) return; // kfx: the motion layer owns reveals\n" },
  { find: /\(function parallaxBlobs\(\)\{\n(?!\s*if \(window\.kflParallaxInit\) return;)/g,
    put: "(function parallaxBlobs(){\n    if (window.kflParallaxInit) return; // kfx: the motion layer owns parallax\n" },
  { find: /var targets = document\.querySelectorAll\('a\.magnetic-cta, button\.magnetic-cta'\);/g,
    put: "var targets = window.kflPremiumMotionInit ? [] : document.querySelectorAll('a.magnetic-cta, button.magnetic-cta');" },
  { find: /(^|[^(])document\.querySelectorAll\('\.kfl-magnetic(, a\[href="#signup"\])?'\)\.forEach\(/gm,
    put: (m, pre, extra) => pre + "(window.kflPremiumMotionInit ? [] : document.querySelectorAll('.kfl-magnetic" + (extra || '') + "')).forEach(" }
];

function apply(html, profile) {
  let out = html;
  const b = block(profile);
  const re = /<!-- kfx:begin[\s\S]*?<!-- kfx:end -->/;
  if (re.test(out)) out = out.replace(re, b);
  else {
    const i = out.search(/<\/head>/i);
    if (i < 0) throw new Error('no </head>');
    out = out.slice(0, i) + b + '\n' + out.slice(i);
  }
  PATCHES.forEach((p) => { out = out.replace(p.find, p.put); });
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const pages = listPages();
  let changed = 0, stale = [];
  pages.forEach((rel) => {
    const fp = path.join(ROOT, rel);
    const html = fs.readFileSync(fp, 'utf8');
    const next = apply(html, profileOf(rel));
    if (next !== html) {
      if (check) stale.push(rel);
      else { fs.writeFileSync(fp, next); changed++; }
    }
  });
  if (check) {
    if (stale.length) { console.log('kfx rollout stale on ' + stale.length + ' page(s): ' + stale.slice(0, 12).join(', ')); process.exit(1); }
    console.log('kfx rollout up to date on ' + pages.length + ' pages');
    return;
  }
  console.log('kfx rollout: ' + pages.length + ' pages, ' + changed + ' updated');
}

if (require.main === module) main();
module.exports = { listPages, profileOf, apply, block, EXCLUDE, V };
